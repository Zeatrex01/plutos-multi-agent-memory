// plutos rebind (lib/rebind.mjs): after a project moved folder, every client entry that names the
// old folder by an absolute path is rewired, the hub entry moves, shared .plutos/ state comes
// along, and the clients PLUT_OS does not write get their exact manual step. Everything runs in a
// temp folder: HOME, USERPROFILE, APPDATA and PLUTOS_HOME all point there before any import.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'plutos-rebind-'));
const home = path.join(temp, 'home');
fs.mkdirSync(home, { recursive: true });
process.env.HOME = home;
process.env.USERPROFILE = home;
process.env.APPDATA = path.join(home, 'AppData', 'Roaming');
process.env.PLUTOS_HOME = path.join(temp, 'plutos-home');
delete process.env.PLUTOS_MODE;

let passed = 0, failed = 0;
const check = (name, cond, extra = '') => { if (cond) { passed++; console.log(`  ok  ${name}`); } else { failed++; console.log(`  FAIL ${name}${extra ? ' — ' + extra : ''}`); } };
const read = file => fs.readFileSync(file, 'utf8');
const writeJson = (file, data) => { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, JSON.stringify(data, null, 2) + '\n'); };

try {
    const { rebindProject, inferOldPath } = await import('../lib/rebind.mjs');
    const { findClient, configEntry, configPath, isWired, snippet, STUB_REL } = await import('../lib/connect.mjs');
    const workspaces = await import('../lib/workspaces.mjs');

    const oldRoot = path.join(temp, 'old-project');
    const newRoot = path.join(temp, 'new-project');
    const plain = path.join(temp, 'plain');
    for (const dir of [oldRoot, newRoot, plain]) fs.mkdirSync(dir, { recursive: true });

    // --- refusals ------------------------------------------------------------------------
    const notKit = rebindProject(oldRoot, plain);
    check('a folder without PLUT_OS is refused', !!notKit.refused && !notKit.changed.length);
    check('the refusal says what to run', /plutos init/.test(notKit.refused), notKit.refused);

    // The moved project: the tracked launcher came along, the machine configs name the old folder.
    for (const root of [oldRoot, newRoot]) {
        fs.mkdirSync(path.join(root, '.plutos'), { recursive: true });
        fs.writeFileSync(path.join(root, STUB_REL), '// Generated by PLUT_OS\n');
    }
    const same = rebindProject(newRoot, newRoot);
    check('the same folder twice is refused', /same folder/.test(same.refused || ''), same.refused);

    const cursor = findClient('cursor'), gemini = findClient('gemini-cli'), windsurf = findClient('windsurf');
    const zed = findClient('zed'), codex = findClient('codex'), local = findClient('claude-code-local');
    const shared = findClient('claude-code');
    const other = { command: 'npx', args: ['some-server'] };
    writeJson(configPath(cursor, newRoot), { mcpServers: { plutos: configEntry(cursor, oldRoot), other } });
    writeJson(configPath(gemini, newRoot), { mcpServers: { plutos: configEntry(gemini, oldRoot) } });
    writeJson(configPath(shared, newRoot), { mcpServers: { plutos: configEntry(shared, newRoot) } });
    fs.mkdirSync(path.dirname(configPath(codex, newRoot)), { recursive: true });
    fs.writeFileSync(configPath(codex, newRoot), `[mcp_servers.other]\ncommand = "x"\n\n${snippet(codex, oldRoot)}\ncwd = ${JSON.stringify(oldRoot)}\n`);
    // Global configs: Windsurf names the old folder, Zed names some other project.
    // The owner added keys of his own to the Windsurf entry: they must survive the rewrite.
    const windsurfOld = configEntry(windsurf, oldRoot);
    writeJson(configPath(windsurf, newRoot), { mcpServers: { plutos: { ...windsurfOld, args: [...windsurfOld.args, '--verbose'], timeout: 30,
        env: { ...(windsurfOld.env || {}), PLUTOS_LOG: path.join(oldRoot, 'logs', 'mcp.log'), MODE: 'quiet' } } } });
    const elsewhere = path.join(temp, 'another-project');
    writeJson(configPath(zed, newRoot), { context_servers: { plutos: configEntry(zed, elsewhere) } });
    const claudeJson = path.join(home, '.claude.json');
    writeJson(claudeJson, { projects: { [oldRoot]: { mcpServers: { plutos: configEntry(local, oldRoot) } } } });
    // Shared state left behind in the old folder; the new one already has its own packs.json.
    fs.writeFileSync(path.join(oldRoot, '.plutos', 'drawers.json'), '{"open":["code"]}');
    fs.writeFileSync(path.join(oldRoot, '.plutos', 'packs.json'), '{"old":true}');
    fs.writeFileSync(path.join(newRoot, '.plutos', 'packs.json'), '{"new":true}');
    fs.writeFileSync(path.join(oldRoot, '.plutos', 'local.json'), '{"machine":true}');
    workspaces.addWorkspace(oldRoot);

    check('the old folder is found from the configs that moved along', JSON.stringify(inferOldPath(newRoot)) === JSON.stringify([path.resolve(oldRoot)]), JSON.stringify(inferOldPath(newRoot)));

    // --- dry run -------------------------------------------------------------------------
    const files = [configPath(cursor, newRoot), configPath(gemini, newRoot), configPath(windsurf, newRoot), configPath(zed, newRoot), claudeJson, configPath(codex, newRoot)];
    const before = files.map(read);
    const dry = rebindProject(undefined, newRoot, { dryRun: true });
    check('a dry run without --from uses the inferred old folder', dry.from === path.resolve(oldRoot) && !dry.refused, dry.refused);
    check('a dry run writes no client config', files.every((f, i) => read(f) === before[i]));
    check('a dry run lists what it would rewrite', dry.changed.filter(c => /would rewrite/.test(c)).length === 3, dry.changed.join(' | '));
    check('a dry run leaves the hub and the shared state alone',
        workspaces.getWorkspaces().includes(oldRoot) && !fs.existsSync(path.join(newRoot, '.plutos', 'drawers.json')));

    // --- the rebind ------------------------------------------------------------------------
    const r = rebindProject(oldRoot, newRoot);
    check('no refusal', !r.refused, r.refused);
    check('Cursor now points at the new folder', isWired(cursor, newRoot));
    check('Cursor keeps its other server', JSON.stringify(JSON.parse(read(configPath(cursor, newRoot))).mcpServers.other) === JSON.stringify(other));
    check('Gemini CLI cwd is the new folder', isWired(gemini, newRoot));
    check('Windsurf (global) is rewired', isWired(windsurf, newRoot));
    {
        const ws = JSON.parse(read(configPath(windsurf, newRoot))).mcpServers.plutos;
        check('Windsurf keeps the owner\'s own keys, with old-folder paths moved', ws.timeout === 30 && ws.env?.MODE === 'quiet'
            && ws.env?.PLUTOS_LOG === path.join(newRoot, 'logs', 'mcp.log'), JSON.stringify(ws));
        check('an extra arg it cannot place is named in the notes', r.notes.some(n => /Windsurf.*extra args \("--verbose"\)/.test(n)), r.notes.join(' | '));
        check('the reply says which keys it kept', r.changed.some(c => /Windsurf.*kept your .*timeout/.test(c)), r.changed.join(' | '));
    }
    check('Zed, naming another project, is left alone', read(configPath(zed, newRoot)) === before[3]);
    check('the portable .mcp.json is skipped, not rewritten', r.skipped.some(s => /Claude Code \(team-shared\)/.test(s)), r.skipped.join(' | '));
    check('~/.claude.json is never written', read(claudeJson) === before[4]);
    check('Claude Code local gets the exact claude mcp add command for the new folder',
        r.notes.some(n => n.includes('claude mcp add') && n.includes(`PLUTOS_PROJECT_ROOT=${newRoot}`)), r.notes.join(' | '));
    check('Codex TOML is not merged; its note carries the snippet',
        read(configPath(codex, newRoot)) === before[5] && r.notes.some(n => n.includes('[mcp_servers.plutos]') && n.includes('Codex')));
    const hub = workspaces.getWorkspaces();
    check('the hub entry moved', hub.includes(path.resolve(newRoot)) && !hub.includes(oldRoot), JSON.stringify(hub));
    check('missing shared state is copied', read(path.join(newRoot, '.plutos', 'drawers.json')) === '{"open":["code"]}');
    check('shared state the new folder has is kept', read(path.join(newRoot, '.plutos', 'packs.json')) === '{"new":true}');
    check('machine state is not copied', !fs.existsSync(path.join(newRoot, '.plutos', 'local.json')));
    check('the old folder is untouched', read(path.join(oldRoot, '.plutos', 'packs.json')) === '{"old":true}' && fs.existsSync(path.join(oldRoot, STUB_REL)));
    check('the reply says to restart the clients', r.notes.some(n => /Restart each AI client/.test(n)));

    // --- after the rebind ----------------------------------------------------------------
    const again = rebindProject(undefined, newRoot);
    check('a second rebind without --from finds nothing and says to name it', /--from/.test(again.refused || ''), again.refused);

    // --- Kimi Code: its project .kimi-code/mcp.json carries an absolute cwd ----------------
    {
        const kimi = findClient('kimi-code');
        const kimiOld = path.join(temp, 'kimi-old'), kimiNew = path.join(temp, 'kimi-new');
        for (const dir of [kimiOld, kimiNew]) {
            fs.mkdirSync(path.join(dir, '.plutos'), { recursive: true });
            fs.writeFileSync(path.join(dir, STUB_REL), '// launcher\n');
        }
        writeJson(configPath(kimi, kimiNew), { mcpServers: { plutos: configEntry(kimi, kimiOld), other: { url: 'https://example.invalid/mcp' } } });
        const moved = rebindProject(kimiOld, kimiNew);
        const after = JSON.parse(read(configPath(kimi, kimiNew)));
        check('Kimi Code cwd is rewired to the new folder', !moved.refused && isWired(kimi, kimiNew), moved.refused || JSON.stringify(after));
        check('Kimi Code keeps its other server', after.mcpServers.other?.url === 'https://example.invalid/mcp');
    }
} finally {
    fs.rmSync(temp, { recursive: true, force: true });
}

console.log(`\nrebind: ${passed} passed, ${failed} failed`);
if (failed) process.exit(1);
