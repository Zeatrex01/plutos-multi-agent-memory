export let currentLang = 'en';

// Imported bindings are read-only in ES modules — callers who need to change the
// language (the toggle button) go through this instead of assigning currentLang directly.
export function setLang(lang) {
    currentLang = lang;
}

// Called once on boot, before the first applyLanguage(). Remembers the owner's choice
// across visits (like the theme); with no saved choice, the UI opens in English whatever
// the browser's language. Turkish stays one toggle away.
export function initLanguage() {
    let saved = null;
    try { saved = localStorage.getItem('plutos-lang'); } catch (e) { /* storage blocked */ }
    setLang(saved && translations[saved] ? saved : 'en');
}

export function applyLanguage() {
    const indicator = document.getElementById('lang-indicator');
    if (indicator) indicator.textContent = currentLang.toUpperCase();

    // The story deck opens as its own page, so it cannot read this module — the language
    // rides along in the URL. It is the one output written for the owner to read, which is
    // why it follows the UI language at all while the rest of the server speaks English.
    const deckLink = document.getElementById('deck-link');
    if (deckLink) deckLink.setAttribute('href', `/deck?lang=${encodeURIComponent(currentLang)}`);
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if(translations[currentLang][key]) {
            el.textContent = translations[currentLang][key];
        }
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if(translations[currentLang][key]) {
            el.setAttribute('placeholder', translations[currentLang][key]);
        }
    });
}

export function t(key) {
    return translations[currentLang][key] || key;
}

// The system-bar button (dashboard-ui.html) — previously dead: applyLanguage() already
// looked for #lang-indicator, but nothing in the UI ever called setLang(), so the language
// could never actually change. Only two languages exist, so a flip is enough — no menu.
window.toggleLanguage = function() {
    const langs = Object.keys(translations);
    const next = langs[(langs.indexOf(currentLang) + 1) % langs.length];
    setLang(next);
    try { localStorage.setItem('plutos-lang', next); } catch (e) { /* storage blocked */ }
    applyLanguage();
    // data-i18n covers the static chrome; whatever tab is open was rendered with t() calls
    // baked into its HTML and needs a re-fetch to actually show the new language.
    if (window.refreshActiveView) window.refreshActiveView();
};
